package dev.tessera.compiler.codegen;

import static dev.tessera.compiler.JavaStrings.literal;
import static dev.tessera.compiler.codegen.TemplateGenerator.javaName;

import dev.tessera.compiler.codegen.attr.FragmentMethods;
import dev.tessera.compiler.html.HtmlParser;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;

/** Assembles the generated template class (shape in docs/mvp-design.md) around a render body. */
final class TemplateClassSource {
  private static final String RT = "dev.tessera.runtime.";

  private TemplateClassSource() {}

  /**
   * The Java source of {@code info}'s class.
   *
   * @param constants static text to constant name, in declaration order
   * @param members extra members (fragment methods, helpers), appended in order
   * @param body the statements of the render method
   */
  static String render(
      TemplateIndex.TemplateInfo info, Map<String, String> constants, List<String> members, String body) {
    String fqcn = info.className();
    int dot = fqcn.lastIndexOf('.');
    String pkg = dot < 0 ? "" : fqcn.substring(0, dot);
    String simple = fqcn.substring(dot + 1);
    String io = RT + "RenderContext ctx, " + RT + "Output out";
    List<String> decls = new ArrayList<>();
    List<String> names = new ArrayList<>();
    for (TemplateIndex.Param p : info.params()) {
      decls.add(p.javaType() + " " + javaName(p.name()));
      names.add(javaName(p.name()));
    }
    String declList = String.join(", ", decls);
    String nameList = String.join(", ", names);

    StringBuilder sb = new StringBuilder();
    if (!pkg.isEmpty()) {
      sb.append("package ").append(pkg).append(";\n\n");
    }
    sb.append("/** Generated by Tessera from ")
        .append(javadocSafe(info.document().source().path()))
        .append(". Do not edit. */\n");
    sb.append("public final class ").append(simple).append(" implements ").append(RT).append("Template {\n");
    constants.forEach(
        (text, name) ->
            sb.append("  private static final java.lang.String ").append(name).append(" = ").append(literal(text)).append(";\n"));
    for (String d : decls) {
      sb.append("  private final ").append(d).append(";\n");
    }
    sb.append("\n  private ").append(simple).append("(").append(declList).append(") {\n");
    for (String n : names) {
      sb.append("    this.").append(n).append(" = ").append(n).append(";\n");
    }
    sb.append("  }\n\n");
    sb.append("  public static ").append(simple).append(" of(").append(declList).append(") {\n");
    sb.append("    return new ").append(simple).append("(").append(nameList).append(");\n  }\n\n");
    sb.append("  @Override\n  public java.lang.String templateName() {\n    return ")
        .append(literal(info.viewName()))
        .append(";\n  }\n\n");
    sb.append("  @Override\n  public void render(").append(io).append(") {\n");
    if (info.params().isEmpty()) {
      // A static render(ctx, out) would clash with this method; the body lives here.
      sb.append(body).append("  }\n");
    } else {
      sb.append("    render(").append(nameList).append(", ctx, out);\n  }\n\n");
      sb.append("  public static void render(").append(declList).append(", ").append(io).append(") {\n");
      // A Fragment page parameter comes from Java: only a Fragment.of (#581).
      sb.append(FragmentMethods.requireVerified(info.viewName(), info.params()));
      sb.append(body).append("  }\n");
    }
    for (String m : members) {
      sb.append('\n').append(m).append('\n');
    }
    sb.append("}\n");
    return sb.toString();
  }

  /**
   * {@code source} (a class {@link #render} wrote) marked as a verified {@code FLOW} partial (#396):
   * it overrides {@code Template.verifiedFlowPartial()} to return true. The verifier decides this
   * after the class is generated, from its skeleton, so the mark is added to the finished source.
   */
  static String markFlowPartial(String source) {
    if (!source.endsWith("}\n")) {
      throw new IllegalArgumentException("not a generated template class");
    }
    return source.substring(0, source.length() - 2)
        + "\n  /** The verifier proved this template a FLOW partial (#396). */\n"
        + "  @Override\n  public boolean verifiedFlowPartial() {\n    return true;\n  }\n}\n";
  }

  /** Keeps a file name harmless inside a comment (no comment end, no unicode escapes). */
  private static String javadocSafe(String s) {
    StringBuilder sb = new StringBuilder();
    for (int i = 0; i < s.length(); i++) {
      char c = s.charAt(i);
      sb.append(HtmlParser.isAsciiAlphanumeric(c) || "/._-".indexOf(c) >= 0 ? c : '_');
    }
    return sb.toString();
  }
}
