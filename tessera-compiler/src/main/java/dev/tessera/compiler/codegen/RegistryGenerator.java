package dev.tessera.compiler.codegen;

import static dev.tessera.compiler.JavaStrings.literal;

import dev.tessera.compiler.Backports;
import dev.tessera.compiler.CompilerEnv;
import dev.tessera.compiler.GeneratedFile;
import java.util.ArrayList;
import java.util.List;
import javax.lang.model.type.PrimitiveType;
import javax.lang.model.type.TypeMirror;

/**
 * Generates {@code <basePackage>.TesseraRegistry implements dev.tessera.runtime.TemplateRegistry}
 * (one {@code TemplateEntry} per template whose renderer adapts a model map with
 * {@code instanceof} checks; no reflection) and the
 * {@code META-INF/services/dev.tessera.runtime.TemplateRegistry} resource naming it.
 *
 * <p>Model adaptation per parameter: a missing (or null) value is passed as {@code null}; a value
 * that is not an instance of the parameter's erased type throws {@code TemplateModelException}
 * naming the template, the parameter, the expected and the actual type. Generic arguments are
 * not checked. A primitive parameter needs a value of its box type; a missing one throws.
 */
public final class RegistryGenerator {
  public static final String SERVICES_FILE = "META-INF/services/dev.tessera.runtime.TemplateRegistry";
  private static final String RT = "dev.tessera.runtime.";

  private final CompilerEnv env;
  private final TemplateIndex index;

  public RegistryGenerator(CompilerEnv env, TemplateIndex index) {
    this.env = env;
    this.index = index;
  }

  public List<GeneratedFile> generate() {
    if (index.templates().isEmpty()) {
      return Backports.listOf();
    }
    String fqcn = ClassNames.qualify(env.basePackage(), ClassNames.REGISTRY);
    return Backports.listOf(
        new GeneratedFile(GeneratedFile.Kind.JAVA, fqcn, source()),
        new GeneratedFile(GeneratedFile.Kind.RESOURCE, SERVICES_FILE, fqcn + "\n"));
  }

  private String source() {
    String entry = RT + "TemplateEntry";
    StringBuilder sb = new StringBuilder();
    if (!env.basePackage().isEmpty()) {
      sb.append("package ").append(env.basePackage()).append(";\n\n");
    }
    sb.append("/** Generated by Tessera: every compiled template of this module. Do not edit. */\n");
    sb.append("public final class ").append(ClassNames.REGISTRY).append(" implements ").append(RT).append("TemplateRegistry {\n");
    sb.append("  private static final java.util.List<").append(entry).append("> ENTRIES =\n");
    sb.append("      java.util.Collections.unmodifiableList(java.util.Arrays.asList(");
    List<TemplateIndex.TemplateInfo> templates = index.templates();
    for (int i = 0; i < templates.size(); i++) {
      TemplateIndex.TemplateInfo t = templates.get(i);
      List<String> params = new ArrayList<>();
      for (TemplateIndex.Param p : t.params()) {
        params.add("new " + entry + ".Param(" + literal(p.name()) + ", " + literal(p.javaType()) + ")");
      }
      sb.append(i == 0 ? "\n" : ",\n")
          .append("          new ")
          .append(entry)
          .append("(")
          .append(literal(t.viewName()))
          .append(params.isEmpty() ? ", java.util.Collections.emptyList(), " : ", java.util.Arrays.asList(")
          .append(String.join(", ", params))
          .append(params.isEmpty() ? "" : "), ")
          .append(ClassNames.REGISTRY)
          .append("::render$")
          .append(i)
          .append(")");
    }
    sb.append("));\n");
    sb.append("  private static final java.util.Map<java.lang.String, ").append(entry).append("> BY_NAME = new java.util.HashMap<>();\n\n");
    sb.append("  static {\n    for (").append(entry).append(" e : ENTRIES) {\n      BY_NAME.put(e.name(), e);\n    }\n  }\n\n");
    sb.append("  @Override\n  public java.util.Optional<").append(entry).append("> find(java.lang.String viewName) {\n");
    sb.append("    return java.util.Optional.ofNullable(viewName == null ? null : BY_NAME.get(viewName));\n  }\n\n");
    sb.append("  @Override\n  public java.util.Collection<").append(entry).append("> all() {\n    return ENTRIES;\n  }\n");
    for (int i = 0; i < templates.size(); i++) {
      sb.append('\n').append(adapter(i, templates.get(i)));
    }
    sb.append("\n  private static ").append(RT).append("TemplateModelException mismatch(\n");
    sb.append("      java.lang.String template, java.lang.String param, java.lang.String expected, java.lang.Object actual) {\n");
    sb.append("    return new ").append(RT).append("TemplateModelException(\n");
    sb.append("        \"template '\" + template + \"': model attribute '\" + param + \"' must be \" + expected\n");
    sb.append("            + (actual == null ? \" but is missing\" : \" but is \" + actual.getClass().getName()));\n");
    sb.append("  }\n}\n");
    return sb.toString();
  }

  private String adapter(int i, TemplateIndex.TemplateInfo t) {
    StringBuilder sb = new StringBuilder();
    sb.append("  @SuppressWarnings(\"unchecked\")\n");
    sb.append("  private static void render$")
        .append(i)
        .append("(java.util.Map<java.lang.String, ?> model, ")
        .append(RT)
        .append("RenderContext ctx, ")
        .append(RT)
        .append("Output out) {\n");
    List<String> args = new ArrayList<>();
    List<TemplateIndex.Param> params = t.params();
    for (int j = 0; j < params.size(); j++) {
      TemplateIndex.Param p = params.get(j);
      String v = "a$" + j;
      String fail =
          "throw mismatch(" + literal(t.viewName()) + ", " + literal(p.name()) + ", " + literal(p.javaType()) + ", " + v + ");";
      sb.append("    java.lang.Object ").append(v).append(" = model.get(").append(literal(p.name())).append(");\n");
      TypeMirror type = p.type();
      if (type instanceof PrimitiveType) {
        String box = env.types().boxedClass((PrimitiveType) type).getQualifiedName().toString();
        sb.append("    if (!(").append(v).append(" instanceof ").append(box).append(")) {\n      ").append(fail).append("\n    }\n");
        args.add("(" + box + ") " + v);
      } else {
        String erased = env.types().erasure(type).toString();
        sb.append("    if (")
            .append(v)
            .append(" != null && !(")
            .append(v)
            .append(" instanceof ")
            .append(erased)
            .append(")) {\n      ")
            .append(fail)
            .append("\n    }\n");
        args.add("(" + p.javaType() + ") " + v);
      }
    }
    if (params.isEmpty()) {
      sb.append("    ").append(t.className()).append(".of().render(ctx, out);\n");
    } else {
      sb.append("    ")
          .append(t.className())
          .append(".render(")
          .append(String.join(", ", args))
          .append(", ctx, out);\n");
    }
    sb.append("  }\n");
    return sb.toString();
  }
}
