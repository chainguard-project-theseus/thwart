package dev.tessera.compiler.codegen.attr;

import dev.tessera.compiler.codegen.AttributeProcessor;
import dev.tessera.compiler.codegen.CodegenContext;
import dev.tessera.compiler.codegen.ElementPlan;
import dev.tessera.compiler.codegen.TemplateIndex;
import dev.tessera.compiler.model.Attribute;
import dev.tessera.compiler.types.Scope;

/**
 * {@code t:fragment="name(Type a)"}: when the enclosing template renders as a whole, a fragment with parameters is removed (it needs arguments); a parameterless one renders in place. The fragment methods themselves are generated by {@link FragmentMethods}.
 *
 * <p>In place, a parameterless fragment renders in an empty scope, exactly as its
 * {@code fragment_<name>} method does: a fragment never sees its surroundings.
 */
public final class FragmentProcessor implements AttributeProcessor {

  @Override
  public void process(CodegenContext ctx, Attribute attr, ElementPlan plan) {
    TemplateIndex.FragmentInfo info =
        ctx.template().fragments().values().stream()
            .filter(f -> f.element() == plan.element())
            .findFirst()
            .orElse(null);
    if (info == null || !info.params().isEmpty()) {
      // Parameterized (or an invalid signature, already reported by TemplateIndex).
      plan.remove();
      return;
    }
    plan.scope(Scope.empty());
  }
}
